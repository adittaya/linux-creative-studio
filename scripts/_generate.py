def pkg_rel(app):
    if app["id"] in EXTRA_DIRS:
        sub = EXTRA_DIRS[app["id"]]
        return f"packages/{app['category']}/{sub}" if "/" not in sub else f"packages/{sub}"
    return f"packages/{app['category']}/{app['id']}"


def w(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def j(path: Path, data):
    w(path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def manifest(app):
    d = dict(app)
    pkg = pkg_rel(app)
    d["package_path"] = pkg
    d["metadata_path"] = f"{pkg}/metadata/application.json"
    d["launch_command"] = f"studioctl launch {app['id']}"
    d["documentation"] = f"docs/applications/{app['id']}.md"
    d["verification_command"] = f"studioctl verify --id {app['id']}"
    d["how_to_use"] = (
        f"Run `studioctl info {app['id']}` for capabilities and formats, "
        f"`studioctl plan --task '...'` to confirm it fits the task, then "
        f"`studioctl launch {app['id']}` (add --dry-run to preview)."
    )
    d["install_status"] = "not-installed-in-this-scaffold" if not app["facade_of"] else "capability-facet"
    d["artifact_status"] = "not-cached" if not app["facade_of"] else "not-applicable"
    return d


